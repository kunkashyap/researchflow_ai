"""
tools/tavily_search.py
Tavily Search API wrapper for the Search Agent.

Wraps the Tavily Python SDK to:
1. Execute a single search query and return structured results.
2. Execute multiple queries and merge/deduplicate the results.
3. Convert raw Tavily results into our internal ResearchSource format.

Security note: Search queries are generated by an LLM and must be treated
as user-influenced input. No special handling is required beyond the normal
Tavily API call, but we validate that result URLs are safe before returning them.
"""

from __future__ import annotations

import time
from typing import Optional

from tavily import TavilyClient

from models.schemas import ResearchSource
from utils.config import config
from utils.helpers import is_safe_url, deduplicate_urls, source_id_from_index
from utils.logging_config import setup_logging

logger = setup_logging("researchflow.tavily")


class TavilySearchTool:
    """
    Wraps Tavily's Python SDK to provide multi-query search with
    deduplication, relevance-score sorting and source ID assignment.
    """

    def __init__(self, api_key: Optional[str] = None):
        self._client = TavilyClient(api_key=api_key or config.TAVILY_API_KEY)

    # -----------------------------------------------------------------------
    # Single Query
    # -----------------------------------------------------------------------

    def search_single(
        self,
        query: str,
        search_depth: str = "basic",
        max_results: int = 5,
        include_raw_content: bool = True,
    ) -> list[dict]:
        """
        Execute one Tavily search and return raw result dicts.

        Args:
            query:            The search string.
            search_depth:     'basic' or 'advanced'.
            max_results:      How many results to retrieve.
            include_raw_content: Whether to fetch the raw page text from Tavily.

        Returns:
            List of raw result dicts from Tavily.
        """
        logger.info("Searching Tavily: '%s' (depth=%s, max=%d)", query, search_depth, max_results)
        try:
            response = self._client.search(
                query=query,
                search_depth=search_depth,
                max_results=max_results,
                include_raw_content=include_raw_content,
            )
            results = response.get("results", [])
            logger.info("Tavily returned %d results for query: '%s'", len(results), query)
            return results
        except Exception as exc:
            logger.error("Tavily search failed for query '%s': %s", query, exc)
            return []

    # -----------------------------------------------------------------------
    # Multi-Query Search
    # -----------------------------------------------------------------------

    def search_multiple(
        self,
        queries: list[str],
        search_depth: str = "basic",
        max_results_per_query: int = 5,
        total_max_results: int = 10,
        delay_between_queries: float = 0.5,
    ) -> list[ResearchSource]:
        """
        Execute multiple search queries, merge results, deduplicate by URL,
        and assign stable source IDs.

        Args:
            queries:                   List of search query strings.
            search_depth:              Tavily depth parameter.
            max_results_per_query:     Results to fetch per query.
            total_max_results:         Cap on total merged results.
            delay_between_queries:     Seconds to pause between requests (rate limiting).

        Returns:
            Deduplicated, ranked list of ResearchSource objects.
        """
        raw_results: list[dict] = []

        for idx, query in enumerate(queries):
            if idx > 0:
                time.sleep(delay_between_queries)
            results = self.search_single(
                query=query,
                search_depth=search_depth,
                max_results=max_results_per_query,
            )
            raw_results.extend(results)

        logger.info("Total raw Tavily results before dedup: %d", len(raw_results))

        # Deduplicate by URL (using our helper that normalises URLs)
        unique_raw = deduplicate_urls(raw_results)

        # Filter out unsafe URLs (localhost, private IPs)
        safe_raw = [r for r in unique_raw if is_safe_url(r.get("url", ""))]

        # Sort by Tavily relevance score (descending)
        safe_raw.sort(key=lambda r: r.get("score", 0.0), reverse=True)

        # Cap to max_results
        capped = safe_raw[:total_max_results]

        # Convert to ResearchSource objects
        sources = [
            self._to_research_source(raw, source_id_from_index(i))
            for i, raw in enumerate(capped)
        ]

        logger.info("Final source count after dedup + filter: %d", len(sources))
        return sources

    # -----------------------------------------------------------------------
    # Conversion
    # -----------------------------------------------------------------------

    @staticmethod
    def _to_research_source(raw: dict, source_id: str) -> ResearchSource:
        """Convert a raw Tavily result dict to a typed ResearchSource."""
        return ResearchSource(
            source_id=source_id,
            title=raw.get("title", ""),
            url=raw.get("url", ""),
            snippet=raw.get("content", "")[:500],  # Tavily's content is a snippet
            published_date=raw.get("published_date"),
            relevance_score=float(raw.get("score", 0.0)),
            # Store the full raw content as a fallback for the Reader Agent
            tavily_content=raw.get("raw_content") or raw.get("content", ""),
        )
